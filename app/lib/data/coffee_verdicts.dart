/// Rolls a random coffee verdict. If [avoid] is given and the first roll
/// lands on the exact same verdict again, it's rerolled once — a small
/// nudge against back-to-back repeats reading as "the app is stuck".
CoffeeVerdict rollCoffeeVerdict(Random random, {CoffeeVerdict? avoid}) {
  final first = coffeeVerdicts[random.nextInt(coffeeVerdicts.length)];
  if (avoid == null || !identical(first, avoid)) return first;
  return coffeeVerdicts[random.nextInt(coffeeVerdicts.length)];
}
